"""Таблица управления — единственный источник подсказок в игре (plan/10).

Та же таблица лежит в `plan/10_controls.md`, и тест сверяет их построчно
(`tests/test_controls.py`): поменял управление — поменяй обе, иначе тесты
упадут. HUD рисует подсказку прямо из `CONTROLS`, поэтому в игре и в документе
одни и те же слова.
"""

from __future__ import annotations

#: (клавиша, действие) — в порядке строк таблицы plan/10.
CONTROLS: tuple[tuple[str, str], ...] = (
    ("WASD", "движение дрона"),
    ("1–9 / ЛКМ по слоту", "выбор слота хотбара; Shift+колесо листает"),
    ("ПКМ по пустому тайлу", "поставить постройку из выбранного слота; пустой слот: ничего"),
    ("ПКМ (удерж.) по залежи, слот не с постройкой", "скан свойств"),
    ("ЛКМ (удерж.) по залежи", "добыча"),
    ("ЛКМ (удерж.) по реликвии", "изучение"),
    ("ЛКМ (удерж.) по своей постройке", "разобрать: постройка падает на землю предметом"),
    ("ПКМ по зданию с контейнерами", "окно его контейнеров"),
    ("R", "повернуть призрак / конвейер под курсором"),
    ("E", "инвентарь + крафт"),
    ("в окне: ЛКМ/ПКМ/Shift/двойной клик/Q", "как в M3.5"),
    ("Пробел", "пауза"),
    ("Колесо", "зум 0.5×…2×"),
    ("F1", "поле пути врагов"),
    ("F2", "слой света"),
    ("F3", "отладочная панель"),
    ("F4", "галерея графики"),
    ("Esc", "снять фокус поиска / закрыть окно / выход"),
)


def hint_lines() -> tuple[str, ...]:
    """Строки подсказки для HUD: «клавиша — действие»."""
    return tuple(f"{key} — {action}" for key, action in CONTROLS)
